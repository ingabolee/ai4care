"""
judge_benchmark.py -- Automated LLM judge benchmarking pipeline.

Loads evaluation traces generated by evaluate.py, scores them with an
independent panel of judge models drawn from the *registered* MODEL_CONFIGS
(not from the estimator's capacity catalogue, which has no downloadable files),
and writes tidy CSV + JSON artifacts.

Root causes of previous null-score runs (fixed here):
  1. judge_selector built model_id strings via slugify() of estimator catalog
     entries (e.g. "qwen2.5-1.5b-instruct") that had no match in MODEL_CONFIGS,
     causing get_runner() to fall into the dynamic-download path, which failed
     on HPC nodes without internet access, leaving 100% null scores.
  2. Exceptions from failed runner loads were caught silently — the judge loop
     continued with an empty result, which was then written as null to the JSONL.
  3. The partial JSONL resume key used (judge_id, run_id) but run_id was not
     guaranteed present in every record when the file was partially corrupted.

Fixes:
  - Judges are selected *only* from models already registered in MODEL_CONFIGS
    and already downloaded (file exists on disk).  No network access required.
  - Runner load failures are loudly reported and the judge is skipped entirely.
  - The transcript extraction guards against missing/empty turns before scoring.
  - A --judges flag lets the user explicitly specify which model IDs to use.
"""

import argparse
import csv
import json
import logging
import statistics
import time
from datetime import datetime
from pathlib import Path

from llm_judge import LLMJudge, METRIC as JUDGE_METRIC, JUDGE_SCHEMA_VERSION
from panel_aggregator import aggregate_judge_results
from model_registry import MODEL_CONFIGS, MODELS_DIR, get_runner, get_enabled_models

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)

RESULTS_DIR = Path("results")
JUDGE_DIR = RESULTS_DIR / "judge_benchmark"


# ─── TRACE LOADING ────────────────────────────────────────────────────────────

def load_traces(traces_path: Path) -> list[dict]:
    """Load all successful traces from evaluation_traces.jsonl.

    Each line in that file is an outer record:
        {
            "run_id": ...,
            "model_id": ...,      <- candidate (generator) model
            "case_id": ...,
            "case_category": ...,
            "status": "success" | "failed",
            "trace": { "turns": [...], "completeness": ..., ... }
        }

    We return the list of outer records whose status is "success" and whose
    inner trace dict contains at least one dialogue turn.
    """
    if not traces_path.exists():
        logger.error(f"Traces file not found: {traces_path}")
        return []

    loaded = []
    skipped_failed = 0
    skipped_no_turns = 0

    with open(traces_path, "r", encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError as e:
                logger.warning(f"Line {lineno}: JSON decode error — {e}")
                continue

            if rec.get("status") != "success":
                skipped_failed += 1
                continue

            # The trace dict is stored under the "trace" key
            inner_trace = rec.get("trace", {})
            turns = inner_trace.get("turns", [])
            dialogue_turns = [t for t in turns if t.get("role") in ("interviewer", "participant")]
            if not dialogue_turns:
                skipped_no_turns += 1
                continue

            loaded.append(rec)

    logger.info(
        f"Loaded {len(loaded)} valid traces "
        f"({skipped_failed} failed episodes skipped, "
        f"{skipped_no_turns} episodes with no dialogue skipped)."
    )
    return loaded


# ─── JUDGE SELECTION FROM REGISTERED MODELS ──────────────────────────────────

def select_registered_judges(requested_ids: list[str] | None, top_n: int) -> list[str]:
    """Return model IDs to use as judges.

    Only considers models that are:
      (a) registered in MODEL_CONFIGS
      (b) have their GGUF file actually present on disk

    If --judges is specified, those IDs are validated and used.
    Otherwise, up to top_n enabled, downloaded models are chosen.
    """
    available = []
    for model_id, cfg in MODEL_CONFIGS.items():
        local_path = MODELS_DIR / cfg.get("local", "")
        if local_path.exists() and local_path.stat().st_size > 10_000:
            available.append(model_id)

    if not available:
        logger.error(
            "No downloaded model files found in .models/. "
            "Run 'python setup.py' first."
        )
        return []

    if requested_ids:
        valid = []
        for mid in requested_ids:
            if mid in available:
                valid.append(mid)
            else:
                logger.warning(
                    f"Requested judge '{mid}' is not available on disk — skipping. "
                    f"Available: {available}"
                )
        return valid

    # Default: use enabled models, up to top_n
    enabled = [m for m in available if MODEL_CONFIGS[m].get("enabled", False)]
    return enabled[:top_n]


# ─── MAIN ─────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="AI4CARE Judge Benchmark Pipeline")
    parser.add_argument(
        "--judges", type=str, default=None,
        help="Comma-separated model IDs to use as judges (must match MODEL_CONFIGS keys, "
             "e.g. 'general_main,coder_main'). Defaults to all downloaded enabled models."
    )
    parser.add_argument(
        "--top-n", type=int, default=4,
        help="Max number of judges to use when --judges is not specified."
    )
    parser.add_argument(
        "--traces", type=str, default="results/evaluation_traces.jsonl",
        help="Path to evaluation_traces.jsonl produced by evaluate.py."
    )
    parser.add_argument(
        "--out", type=str, default="results/judge_benchmark",
        help="Output directory for CSV and JSON artifacts."
    )
    parser.add_argument(
        "--skip-summary", action="store_true",
        help="Skip writing the JSON summary file."
    )
    args = parser.parse_args()

    # ── 1. Select judges ──────────────────────────────────────────────────────
    requested = [j.strip() for j in args.judges.split(",")] if args.judges else None
    judge_ids = select_registered_judges(requested, top_n=args.top_n)

    if not judge_ids:
        logger.error("No valid judges available. Aborting.")
        return

    print("\n" + "=" * 70)
    print("=== JUDGE SELECTION ===")
    print("=" * 70)
    for jid in judge_ids:
        cfg = MODEL_CONFIGS[jid]
        local = MODELS_DIR / cfg["local"]
        size_mb = local.stat().st_size // (1024 * 1024)
        print(f"  [{jid}]  {cfg['description']}  ({size_mb} MB)")
    print("=" * 70 + "\n")

    # ── 2. Load traces ────────────────────────────────────────────────────────
    traces = load_traces(Path(args.traces))
    if not traces:
        logger.error("No usable traces found. Run evaluate.py first.")
        return
    print(f"Loaded {len(traces)} traces for judge evaluation.\n")

    # ── 3. Setup output + resumability ───────────────────────────────────────
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    partial_path = out_dir / "judges_scores_partial.jsonl"

    # Load already-scored (judge_id, run_id) pairs to avoid re-scoring
    completed: set[tuple[str, str]] = set()
    cached: dict[tuple[str, str], dict] = {}
    if partial_path.exists():
        with open(partial_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    rec = json.loads(line)
                    key = (rec["judge_id"], rec["run_id"])
                    completed.add(key)
                    cached[key] = rec["result"]
                except (json.JSONDecodeError, KeyError):
                    continue
        if completed:
            print(f"Resuming: {len(completed)} (judge, trace) pairs already scored.\n")

    # ── 4. Score traces per judge (sequential model loading) ─────────────────
    # Structure: { run_id: { "outer": outer_rec, "judge_results": [ {judge_id, result}, ... ] } }
    results_by_trace: dict[str, dict] = {
        rec["run_id"]: {"outer": rec, "judge_results": []}
        for rec in traces
    }

    with open(partial_path, "a", encoding="utf-8") as partial_f:
        for judge_id in judge_ids:
            print(f"\n[JUDGE] Loading '{judge_id}' ...")

            try:
                runner = get_runner(judge_id, verbose=False)
            except Exception as e:
                logger.error(
                    f"  FAILED to load runner for '{judge_id}': {e}\n"
                    f"  This judge will be skipped entirely."
                )
                continue

            judge = LLMJudge(judge_id=judge_id, runner=runner)
            n_total = len(traces)
            n_scored = 0
            n_skipped = 0
            n_failed = 0

            for i, outer_rec in enumerate(traces, 1):
                run_id = outer_rec["run_id"]
                key = (judge_id, run_id)

                if key in completed:
                    j_res = cached[key]
                    n_skipped += 1
                else:
                    # Pass the inner trace dict (which has "turns")
                    inner_trace = outer_rec["trace"]
                    j_res = judge.evaluate_interview(inner_trace)

                    if not j_res.get("success"):
                        n_failed += 1
                        logger.debug(
                            f"  [{judge_id}] trace {run_id}: "
                            f"{j_res.get('failure_type')} — {j_res.get('failure_reason')}"
                        )

                    # Persist immediately
                    save_rec = {
                        "judge_id": judge_id,
                        "run_id": run_id,
                        "result": j_res,
                        "timestamp": datetime.utcnow().isoformat(),
                    }
                    partial_f.write(json.dumps(save_rec) + "\n")
                    partial_f.flush()
                    completed.add(key)
                    cached[key] = j_res
                    n_scored += 1

                results_by_trace[run_id]["judge_results"].append({
                    "judge_id": judge_id,
                    "result": j_res,
                })

                if i % 25 == 0 or i == n_total:
                    success_pct = (
                        (n_scored - n_failed) / max(n_scored, 1) * 100
                        if n_scored else 0.0
                    )
                    print(
                        f"  Progress: {i}/{n_total} | "
                        f"new={n_scored} cached={n_skipped} parse_fail={n_failed} | "
                        f"parse_success={success_pct:.0f}%"
                    )

            # Explicitly close + delete the runner to free VRAM/RAM
            try:
                del runner
            except Exception:
                pass
            try:
                del judge
            except Exception:
                pass

    # ── 5. Write tidy CSV artifacts ───────────────────────────────────────────
    print("\n[REPORTING] Writing CSV artifacts...")

    long_csv_path = out_dir / "judge_scores_long.csv"
    aggr_csv_path = out_dir / "panel_aggregated.csv"

    LONG_COLS = [
        "run_id", "iteration_id", "candidate_model_id", "case_id",
        "case_group_id", "question_variant_id", "case_category",
        "judge_id",
        "metric", "metric_version", "score",
        "supporting_evidence",
        "parse_status", "failure_type", "failure_reason",
        "latency_ms", "judge_schema_version",
    ]
    AGGR_COLS = [
        "run_id", "candidate_model_id", "case_id",
        "case_group_id", "question_variant_id", "case_category",
        "metric",
        "panel_median", "disagreement_mad",
        "successful_judges", "total_judges", "panel_status",
        "judge_schema_version",
    ]

    with open(long_csv_path, "w", newline="", encoding="utf-8") as lf, \
         open(aggr_csv_path, "w", newline="", encoding="utf-8") as af:

        long_w = csv.DictWriter(lf, fieldnames=LONG_COLS, extrasaction="ignore")
        long_w.writeheader()
        aggr_w = csv.DictWriter(af, fieldnames=AGGR_COLS, extrasaction="ignore")
        aggr_w.writeheader()

        for run_id, v in results_by_trace.items():
            outer = v["outer"]
            judge_results = v["judge_results"]
            cand_id = outer.get("model_id", "")

            # Long rows — one per judge
            for jr in judge_results:
                jid = jr["judge_id"]
                j_res = jr["result"]
                parse_status = "success" if j_res.get("success") else j_res.get("failure_type", "unknown")
                long_w.writerow({
                    "run_id": run_id,
                    "iteration_id": outer.get("iteration_id", ""),
                    "candidate_model_id": cand_id,
                    "case_id": outer.get("case_id", ""),
                    "case_group_id": outer.get("case_group_id", ""),
                    "question_variant_id": outer.get("question_variant_id", ""),
                    "case_category": outer.get("case_category", ""),
                    "judge_id": jid,
                    "metric": JUDGE_METRIC,
                    "metric_version": j_res.get("metric_version", ""),
                    "score": j_res.get("score"),          # None if failed → shows as empty in CSV
                    "supporting_evidence": j_res.get("supporting_evidence", ""),
                    "parse_status": parse_status,
                    "failure_type": j_res.get("failure_type", ""),
                    "failure_reason": j_res.get("failure_reason", ""),
                    "latency_ms": j_res.get("latency_ms", 0),
                    "judge_schema_version": JUDGE_SCHEMA_VERSION,
                })

            # Aggregated row — one per trace
            raw_results = [jr["result"] for jr in judge_results]
            agg = aggregate_judge_results(raw_results)
            aggr_w.writerow({
                "run_id": run_id,
                "candidate_model_id": cand_id,
                "case_id": outer.get("case_id", ""),
                "case_group_id": outer.get("case_group_id", ""),
                "question_variant_id": outer.get("question_variant_id", ""),
                "case_category": outer.get("case_category", ""),
                "metric": JUDGE_METRIC,
                "panel_median": agg["panel_median"],
                "disagreement_mad": agg["disagreement_mad"],
                "successful_judges": agg["successful_judges"],
                "total_judges": agg["total_judges"],
                "panel_status": agg["status"],
                "judge_schema_version": JUDGE_SCHEMA_VERSION,
            })

    print(f"  -> {long_csv_path}")
    print(f"  -> {aggr_csv_path}")

    # ── 6. JSON summary ───────────────────────────────────────────────────────
    if not args.skip_summary:
        summary_path = out_dir / "judge_benchmark_summary.json"

        total_traces = len(traces)
        per_judge: dict[str, dict] = {}

        for run_id, v in results_by_trace.items():
            for jr in v["judge_results"]:
                jid = jr["judge_id"]
                j_res = jr["result"]
                entry = per_judge.setdefault(jid, {
                    "parse_failures": 0,
                    "latency_sum_ms": 0,
                    "scores": [],
                })
                entry["latency_sum_ms"] += j_res.get("latency_ms", 0)
                if not j_res.get("success"):
                    entry["parse_failures"] += 1
                elif j_res.get("score") is not None:
                    entry["scores"].append(j_res["score"])

        per_judge_summary = {}
        for jid, e in per_judge.items():
            scores = e["scores"]
            per_judge_summary[jid] = {
                "model_description": MODEL_CONFIGS.get(jid, {}).get("description", jid),
                "traces_scored": total_traces,
                "parse_failure_rate": round(e["parse_failures"] / total_traces, 4) if total_traces else 0,
                "mean_latency_ms": round(e["latency_sum_ms"] / total_traces, 1) if total_traces else 0,
                "n_valid_scores": len(scores),
                "mean_score": round(statistics.mean(scores), 4) if scores else None,
                "median_score": statistics.median(scores) if scores else None,
                "metric": JUDGE_METRIC,
            }

        summary = {
            "judge_schema_version": JUDGE_SCHEMA_VERSION,
            "metric": JUDGE_METRIC,
            "timestamp": datetime.utcnow().isoformat(),
            "judges_used": judge_ids,
            "total_traces": total_traces,
            "per_judge": per_judge_summary,
        }

        with open(summary_path, "w", encoding="utf-8") as f:
            json.dump(summary, f, indent=2)
        print(f"  -> {summary_path}")

    # ── 7. Console summary ────────────────────────────────────────────────────
    print("\n" + "=" * 70)
    print("=== BENCHMARK COMPLETE ===")
    print("=" * 70)
    for jid in judge_ids:
        data = per_judge.get(jid, {})
        scores = data.get("scores", [])
        fails = data.get("parse_failures", 0)
        fail_pct = round(fails / total_traces * 100, 1) if total_traces else 0.0
        mean_s = round(statistics.mean(scores), 2) if scores else "—"
        print(
            f"  {jid:<20}  valid={len(scores)}/{total_traces}  "
            f"fail_rate={fail_pct}%  mean_score={mean_s}"
        )
    print("=" * 70 + "\n")


if __name__ == "__main__":
    main()
