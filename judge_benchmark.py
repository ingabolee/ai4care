# ─── TRACE LOADING ────────────────────────────────────────────────────────────

def load_traces(traces_path: Path) -> list[dict]:
    """Load all successful traces from evaluation_traces.jsonl.

    Each line in that file is an outer record:
        {
            "run_id": ...,
            "model_id": ...,      <- candidate (generator) model
            "case_id": ...,
            "case_category": ...,
            "status": "success" | "failed",
            "trace": { "turns": [...], "completeness": ..., ... }
        }

    We return the list of outer records whose status is "success" and whose
    inner trace dict contains at least one dialogue turn.
    """
    if not traces_path.exists():
        logger.error(f"Traces file not found: {traces_path}")
        return []

    loaded = []
    skipped_failed = 0
    skipped_no_turns = 0

    with open(traces_path, "r", encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError as e:
                logger.warning(f"Line {lineno}: JSON decode error - {e}")
                continue

            if rec.get("status") != "success":
                skipped_failed += 1
                continue

            # The trace dict is stored under the "trace" key
            inner_trace = rec.get("trace", {})
            turns = inner_trace.get("turns", [])
            dialogue_turns = [t for t in turns if t.get("role") in ("interviewer", "participant")]
            if not dialogue_turns:
                skipped_no_turns += 1
                continue

            loaded.append(rec)

    logger.info(
        f"Loaded {len(loaded)} valid traces "
        f"({skipped_failed} failed episodes skipped, "
        f"{skipped_no_turns} episodes with no dialogue skipped)."
    )
    return loaded


def balanced_judge_sample(
    traces: list[dict],
    per_model_source: int,
    seed: int = 42,
) -> list[dict]:
    """Return the same reproducible, balanced trace subset for every judge.

    A zero limit keeps every successful trace. Otherwise sampling is stratified
    by candidate model and independent source group, preventing the judge panel
    from being dominated by one model or one document.
    """
    if per_model_source == 0:
        return traces
    strata: dict[tuple[str, str], list[dict]] = {}
    for trace in traces:
        key = (
            str(trace.get("model_id", "unknown")),
            str(trace.get("case_group_id") or trace.get("case_id", "unknown")),
        )
        strata.setdefault(key, []).append(trace)
    rng = random.Random(seed)
    selected = []
    for key in sorted(strata):
        candidates = sorted(
            strata[key],
            key=lambda rec: (str(rec.get("question_variant_id", "")), str(rec.get("run_id", ""))),
        )
        take = min(per_model_source, len(candidates))
        selected.extend(rng.sample(candidates, take))
    selected.sort(key=lambda rec: (
        str(rec.get("model_id", "")),
        str(rec.get("case_group_id") or rec.get("case_id", "")),
        str(rec.get("question_variant_id", "")),
    ))
    return selected


def format_duration(seconds: float) -> str:
    seconds = max(0, int(seconds))
    hours, remainder = divmod(seconds, 3600)
    minutes, secs = divmod(remainder, 60)
    if hours:
        return f"{hours}h {minutes:02d}m"
    if minutes:
        return f"{minutes}m {secs:02d}s"
    return f"{secs}s"


# ─── JUDGE SELECTION ─────────────────────────────────────────────────────────

def _estimator_model_specs(hardware: dict, context_length: int, quant: str,
                           small_count: int, large_count: int) -> list[dict]:
    """Return a capacity-ranked panel with small and large judges represented."""
    candidates = select_judges(
        hardware,
        top_n=len(LLMCapacityEngine.MODEL_CATALOG),
        quant=quant,
        context_length=context_length,
    )
    for candidate in candidates:
        candidate["judge_id"] = f"{candidate['model_id']}_{candidate['quant']}"
        candidate["description"] = candidate["name"]
        candidate["selection_source"] = "hardware_estimator"

    small = [candidate for candidate in candidates if candidate["params_b"] <= 4.0]
    large = [candidate for candidate in candidates if candidate["params_b"] >= 7.0]

    def choose_diverse(pool: list[dict], count: int) -> list[dict]:
        chosen, families = [], set()
        for candidate in pool:
            if len(chosen) >= count:
                break
            if candidate["family"] not in families:
                chosen.append(candidate)
                families.add(candidate["family"])
        if len(chosen) < count:
            chosen_ids = {item["judge_id"] for item in chosen}
            for candidate in pool:
                if len(chosen) >= count:
                    break
                if candidate["judge_id"] not in chosen_ids:
                    chosen.append(candidate)
                    chosen_ids.add(candidate["judge_id"])
        return chosen

    primary_small = choose_diverse(small, small_count)
    primary_large = choose_diverse(large, large_count)
    selected_ids = {candidate["judge_id"] for candidate in primary_small + primary_large}
    fallbacks = [candidate for candidate in small + large
                 if candidate["judge_id"] not in selected_ids]
    return primary_small + primary_large + fallbacks


def _manual_model_specs(requested_ids: list[str], quant: str) -> list[dict]:
    """Build selection metadata for explicit registry/catalog IDs."""
    catalog_by_id = {
        model["name"].lower().replace(" ", "-"): model
        for model in LLMCapacityEngine.MODEL_CATALOG
    }
    specs = []
    for model_id in requested_ids:
        if model_id in MODEL_CONFIGS:
            config = MODEL_CONFIGS[model_id]
            specs.append({
                "model_id": model_id,
                "judge_id": model_id,
                "name": config.get("description", model_id),
                "description": config.get("description", model_id),
                "repo": config.get("repo", ""),
                "family": "registered",
                "params_b": None,
                "quant": "registered",
                "vram_gb": None,
                "selection_source": "manual_override",
            })
            continue

        model = catalog_by_id.get(model_id)
        if model is None or model_id not in GENERATED_REGISTRY:
            logger.warning(f"Requested judge '{model_id}' is not registered; skipping.")
            continue
        resolved_quant = "Q4_K_M" if quant == "auto" else quant
        specs.append({
            "model_id": model_id,
            "judge_id": f"{model_id}_{resolved_quant}",
            "name": model["name"],
            "description": model["name"],
            "repo": model["repo"],
            "family": model["family"],
            "params_b": model["params_b"],
            "quant": resolved_quant,
            "vram_gb": None,
            "selection_source": "manual_override",
        })
    return specs


# ─── MAIN ─────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="AI4CARE Judge Benchmark Pipeline")
    parser.add_argument(
        "--judges", type=str, default=None,
        help="Optional comma-separated model IDs that override estimator selection. "
             "By default the estimator-ranked panel targets three small plus one larger judge."
    )
    parser.add_argument(
        "--top-n", type=int, default=4,
        help="Maximum estimator-ranked judges to use (default: 4)."
    )
    parser.add_argument(
        "--small-judges", type=int, default=3,
        help="Target number of fitting judges up to 4B parameters (default: 3)."
    )
    parser.add_argument(
        "--large-judges", type=int, default=1,
        help="Target number of fitting judges at least 7B parameters (default: 1)."
    )
    parser.add_argument(
        "--quant", choices=["auto", *LLMCapacityEngine.WEIGHT_BYTES_PER_PARAM], default="auto",
        help="Quantization for estimator-selected GGUF models; auto chooses the highest precision that fits."
    )
    parser.add_argument(
        "--context-length", type=int, default=4096,
        help="Context length used by the hardware estimate and judge runner."
    )
    parser.add_argument(
        "--sample-per-model-source", type=int, default=1,
        help="Judge this many traces per candidate-model/source-group pair (default: 1; 0 scores all)."
    )
    parser.add_argument(
        "--sample-seed", type=int, default=42,
        help="Fixed seed for the balanced judge trace sample."
    )
    parser.add_argument(
        "--concurrency", type=int, default=0,
        help="Concurrent trace scores for OpenAI-compatible backends; 0 auto-selects (8 remote, 1 local)."
    )
    parser.add_argument(
        "--experiment-dir", type=str, default=None,
        help="Experiment folder created by evaluate.py; uses its traces and writes judges/ there."
    )
    parser.add_argument(
        "--traces", type=str, default=None,
        help="Optional explicit path to evaluation_traces.jsonl."
    )
    parser.add_argument(
        "--out", type=str, default=None,
        help="Optional judge output directory. Defaults to <experiment-dir>/judges."
    )
    parser.add_argument(
        "--skip-summary", action="store_true",
        help="Skip writing the JSON summary file."
    )
    args = parser.parse_args()
    if args.concurrency < 0:
        parser.error("--concurrency must be 0 (automatic) or a positive integer.")
    if args.top_n < 1 or args.small_judges < 0 or args.large_judges < 0 or args.sample_per_model_source < 0:
        parser.error("--top-n must be positive; judge size and sample targets must be zero or positive.")
    backend = os.environ.get("AI4CARE_BACKEND", "local").lower()
    scoring_concurrency = (args.concurrency or (8 if backend == "openai" else 1))
    if backend != "openai":
        scoring_concurrency = 1
        if args.concurrency > 1:
            logger.info("Local llama.cpp judging stays single-threaded per model to avoid concurrent access to one model instance.")

    experiment_dir = Path(args.experiment_dir) if args.experiment_dir else None
    traces_path = Path(args.traces) if args.traces else (
        experiment_dir / "evaluation_traces.jsonl" if experiment_dir else Path("results/evaluation_traces.jsonl")
    )
    out_dir = Path(args.out) if args.out else (
        experiment_dir / "judges" if experiment_dir else JUDGE_DIR
    )

    # ── 1. Select judges from estimated hardware capacity ─────────────────────
    requested = [j.strip() for j in args.judges.split(",")] if args.judges else None
    hardware = HardwareDetector.get_system_hardware()
    gpu_layers_override = os.environ.get("AI4CARE_GPU_LAYERS")
    n_gpu_layers = int(gpu_layers_override) if gpu_layers_override is not None else (
        -1 if hardware.get("gpu_count", 0) and backend != "openai" else 0
    )
    if requested:
        judge_specs = _manual_model_specs(requested, args.quant)
    else:
        judge_specs = _estimator_model_specs(
            hardware, args.context_length, args.quant,
            args.small_judges, args.large_judges,
        )

    if not judge_specs:
        logger.error("The estimator found no judge model that fits the available memory. Aborting.")
        return

    print("\n" + "=" * 70)
    print("=== ESTIMATOR JUDGE SELECTION ===")
    print("=" * 70)
    print(
        f"  Hardware: {hardware.get('gpu_name', 'Unknown')} | "
        f"memory={hardware.get('vram_gb', 0.0):.2f} GB | "
        f"context={args.context_length:,} | quant={args.quant}"
    )
    for model in judge_specs[:max(args.top_n, 1)]:
        expected = model.get("vram_gb")
        memory_note = f" | estimated={expected:.2f} GB" if expected is not None else ""
        print(
            f"  [{model['judge_id']}] {model['description']} "
            f"({model.get('params_b') or '?'}B, {model['quant']}{memory_note})"
        )
    if not requested:
        selected = judge_specs[:max(args.top_n, 1)]
        selected_small = sum(model.get("params_b", 0) <= 4.0 for model in selected)
        selected_large = sum(model.get("params_b", 0) >= 7.0 for model in selected)
        print(
            f"  Size mix available in selected panel: {selected_small} small / "
            f"{selected_large} large (targets {args.small_judges}/{args.large_judges})."
        )
    if not requested and len(judge_specs) > max(args.top_n, 1):
        print(f"  {len(judge_specs) - max(args.top_n, 1)} lower-ranked fitting models retained as load fallbacks.")
    print("=" * 70 + "\n")

    # ── 2. Load traces ────────────────────────────────────────────────────────
    all_traces = load_traces(traces_path)
    if not all_traces:
        logger.error("No usable traces found. Run evaluate.py first.")
        return
    traces = balanced_judge_sample(all_traces, args.sample_per_model_source, args.sample_seed)
    strata_counts: dict[str, int] = {}
    for trace in traces:
        key = str(trace.get("model_id", "unknown")) + "|" + str(
            trace.get("case_group_id") or trace.get("case_id", "unknown")
        )
        strata_counts[key] = strata_counts.get(key, 0) + 1
    print(
        f"Loaded {len(all_traces)} successful traces; judging {len(traces)} balanced traces "
        f"({args.sample_per_model_source or 'all'} per model/source group).\n"
    )

    # ── 3. Setup output + resumability ───────────────────────────────────────
    out_dir.mkdir(parents=True, exist_ok=True)
    partial_path = out_dir / "judges_scores_partial.jsonl"

    # Load already-scored (judge_id, run_id) pairs to avoid re-scoring
    completed: set[tuple[str, str]] = set()
    cached: dict[tuple[str, str], dict] = {}
    if partial_path.exists():
        with open(partial_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    rec = json.loads(line)
                    key = (rec["judge_id"], rec["run_id"])
                    completed.add(key)
                    cached[key] = rec["result"]
                except (json.JSONDecodeError, KeyError):
                    continue
        if completed:
            print(f"Resuming: {len(completed)} (judge, trace) pairs already scored.\n")

    # ── 4. Score traces per judge (one loaded model at a time) ────────────────
    # Structure: { run_id: { "outer": outer_rec, "judge_results": [ {judge_id, result}, ... ] } }
    results_by_trace: dict[str, dict] = {
        rec["run_id"]: {"outer": rec, "judge_results": []}
        for rec in traces
    }
    loaded_judge_specs: list[dict] = []
    model_load_times_ms: dict[str, int] = {}
    target_judge_count = max(args.top_n, 1)

    with open(partial_path, "a", encoding="utf-8") as partial_f:
        for model_spec in judge_specs:
            if not requested and len(loaded_judge_specs) >= target_judge_count:
                break

            judge_id = model_spec["judge_id"]
            model_id = model_spec["model_id"]
            n_total = len(traces)
            n_scored = 0
            n_skipped = 0
            n_failed = 0
            pending = []
            for outer_rec in traces:
                run_id = outer_rec["run_id"]
                key = (judge_id, run_id)
                if key in completed:
                    j_res = cached[key]
                    n_skipped += 1
                    results_by_trace[run_id]["judge_results"].append({
                        "judge_id": judge_id, "result": j_res,
                    })
                else:
                    pending.append(outer_rec)

            if not pending:
                loaded_judge_specs.append(model_spec)
                model_load_times_ms[model_spec["judge_id"]] = 0
                print(
                    f"\n[JUDGE] {judge_id}: all {n_total} traces already scored; "
                    "model loading skipped.",
                    flush=True,
                )
                continue

            print(
                f"\n[JUDGE] Loading '{model_spec['name']}' ({model_spec['quant']}); "
                f"{len(pending)} new / {n_skipped} cached traces ...",
                flush=True,
            )

            model_load_started = time.perf_counter()
            try:
                runner = get_runner(
                    model_id,
                    verbose=False,
                    quant=model_spec["quant"] if model_spec["quant"] != "registered" else "Q4_K_M",
                    n_ctx=args.context_length,
                    n_gpu_layers=n_gpu_layers,
                )
                model_load_times_ms[model_spec["judge_id"]] = int(
                    (time.perf_counter() - model_load_started) * 1000
                )
            except Exception as e:
                logger.error(
                    f"  FAILED to load runner for '{model_id}': {e}\n"
                    f"  Trying the next estimator-ranked fitting model if available."
                )
                continue

            loaded_judge_specs.append(model_spec)
            judge = LLMJudge(judge_id=judge_id, runner=runner)
            score_started = time.perf_counter()

            def save_scored(outer_rec, j_res):
                nonlocal n_scored, n_failed
                run_id = outer_rec["run_id"]
                if not j_res.get("success"):
                    n_failed += 1
                save_rec = {
                    "judge_id": judge_id,
                    "run_id": run_id,
                    "result": j_res,
                    "timestamp": datetime.utcnow().isoformat(),
                }
                partial_f.write(json.dumps(save_rec) + "\n")
                partial_f.flush()
                completed.add((judge_id, run_id))
                cached[(judge_id, run_id)] = j_res
                results_by_trace[run_id]["judge_results"].append({
                    "judge_id": judge_id, "result": j_res,
                })
                n_scored += 1
                done = n_scored + n_skipped
                elapsed = max(time.perf_counter() - score_started, 0.1)
                rate = n_scored / elapsed
                eta = format_duration((n_total - done) / rate) if rate else "estimating"
                success_pct = (n_scored - n_failed) / max(n_scored, 1) * 100
                print(
                    f"  Progress [{judge_id}]: {done}/{n_total} | new={n_scored} "
                    f"cached={n_skipped} parse_fail={n_failed} | "
                    f"parse_success={success_pct:.0f}% | elapsed={format_duration(elapsed)} "
                    f"ETA={eta}",
                    flush=True,
                )

            if scoring_concurrency == 1:
                for outer_rec in pending:
                    save_scored(outer_rec, judge.evaluate_interview(outer_rec["trace"]))
            else:
                with ThreadPoolExecutor(max_workers=scoring_concurrency) as score_pool:
                    futures = {
                        score_pool.submit(judge.evaluate_interview, outer_rec["trace"]): outer_rec
                        for outer_rec in pending
                    }
                    for future in as_completed(futures):
                        save_scored(futures[future], future.result())

            # Scores are flushed individually above so an interrupted judge run
            # resumes from its most recent completed trace.
            partial_f.flush()

            # Explicitly close + delete the runner to free VRAM/RAM
            try:
                del runner
            except Exception:
                pass
            try:
                del judge
            except Exception:
                pass

    if not loaded_judge_specs:
        logger.error("No selected judge model could be loaded. No score files were written.")
        return

    actual_small = sum(
        (model.get("params_b") or 0) <= 4.0 for model in loaded_judge_specs
    )
    actual_large = sum(
        (model.get("params_b") or 0) >= 7.0 for model in loaded_judge_specs
    )
    if requested:
        judge_panel_complete = len(loaded_judge_specs) == len(judge_specs)
    else:
        judge_panel_complete = (
            len(loaded_judge_specs) >= target_judge_count
            and actual_small >= args.small_judges
            and actual_large >= args.large_judges
        )
    if not judge_panel_complete and not requested:
        logger.warning(
            "Loaded judge panel is smaller than requested by size: %s small / %s large; "
            "requested %s / %s. See the manifest for the exact panel used.",
            actual_small, actual_large, args.small_judges, args.large_judges,
        )

    judge_ids = [model["judge_id"] for model in loaded_judge_specs]
    judge_metadata = {model["judge_id"]: model for model in loaded_judge_specs}

    # ── 5. Write tidy CSV artifacts ───────────────────────────────────────────
    print("\n[REPORTING] Writing CSV artifacts...")

    long_csv_path = out_dir / "judge_scores_long.csv"
    aggr_csv_path = out_dir / "panel_aggregated.csv"

    LONG_COLS = [
        "experiment_id", "run_profile", "run_id", "iteration_id", "candidate_model_id", "case_id",
        "case_group_id", "question_variant_id", "case_category",
        "judge_id", "judge_model_name", "judge_params_b", "judge_quant",
        "judge_estimated_memory_gb", "judge_context_length",
        "metric", "metric_version", "score",
        "supporting_evidence",
        "parse_status", "failure_type", "failure_reason",
        "latency_ms", "prompt_tokens", "completion_tokens", "judge_schema_version",
    ]
    AGGR_COLS = [
        "experiment_id", "run_profile", "run_id", "candidate_model_id", "case_id",
        "case_group_id", "question_variant_id", "case_category",
        "metric",
        "panel_median", "disagreement_mad",
        "successful_judges", "total_judges", "panel_status",
        "judge_schema_version",
    ]

    with open(long_csv_path, "w", newline="", encoding="utf-8") as lf, \
         open(aggr_csv_path, "w", newline="", encoding="utf-8") as af:

        long_w = csv.DictWriter(lf, fieldnames=LONG_COLS, extrasaction="ignore")
        long_w.writeheader()
        aggr_w = csv.DictWriter(af, fieldnames=AGGR_COLS, extrasaction="ignore")
        aggr_w.writeheader()

        for run_id, v in results_by_trace.items():
            outer = v["outer"]
            judge_results = v["judge_results"]
            cand_id = outer.get("model_id", "")

            # Long rows — one per judge
            for jr in judge_results:
                jid = jr["judge_id"]
                j_res = jr["result"]
                model_meta = judge_metadata.get(jid, {})
                parse_status = "success" if j_res.get("success") else j_res.get("failure_type", "unknown")
                long_w.writerow({
                    "experiment_id": outer.get("experiment_id", experiment_dir.name if experiment_dir else ""),
                    "run_profile": outer.get("run_profile", ""),
                    "run_id": run_id,
                    "iteration_id": outer.get("iteration_id", ""),
                    "candidate_model_id": cand_id,
                    "case_id": outer.get("case_id", ""),
                    "case_group_id": outer.get("case_group_id", ""),
                    "question_variant_id": outer.get("question_variant_id", ""),
                    "case_category": outer.get("case_category", ""),
                    "judge_id": jid,
                    "judge_model_name": model_meta.get("name", jid),
                    "judge_params_b": model_meta.get("params_b"),
                    "judge_quant": model_meta.get("quant", ""),
                    "judge_estimated_memory_gb": model_meta.get("vram_gb"),
                    "judge_context_length": model_meta.get("context_length", args.context_length),
                    "metric": JUDGE_METRIC,
                    "metric_version": j_res.get("metric_version", ""),
                    "score": j_res.get("score"),          # None if failed → shows as empty in CSV
                    "supporting_evidence": j_res.get("supporting_evidence", ""),
                    "parse_status": parse_status,
                    "failure_type": j_res.get("failure_type", ""),
                    "failure_reason": j_res.get("failure_reason", ""),
                    "latency_ms": j_res.get("latency_ms", 0),
                    "prompt_tokens": j_res.get("prompt_tokens", 0),
                    "completion_tokens": j_res.get("completion_tokens", 0),
                    "judge_schema_version": JUDGE_SCHEMA_VERSION,
                })

            # Aggregated row — one per trace
            raw_results = [jr["result"] for jr in judge_results]
            agg = aggregate_judge_results(raw_results)
            aggr_w.writerow({
                "experiment_id": outer.get("experiment_id", experiment_dir.name if experiment_dir else ""),
                "run_profile": outer.get("run_profile", ""),
                "run_id": run_id,
                "candidate_model_id": cand_id,
                "case_id": outer.get("case_id", ""),
                "case_group_id": outer.get("case_group_id", ""),
                "question_variant_id": outer.get("question_variant_id", ""),
                "case_category": outer.get("case_category", ""),
                "metric": JUDGE_METRIC,
                "panel_median": agg["panel_median"],
                "disagreement_mad": agg["disagreement_mad"],
                "successful_judges": agg["successful_judges"],
                "total_judges": agg["total_judges"],
                "panel_status": agg["status"],
                "judge_schema_version": JUDGE_SCHEMA_VERSION,
            })

    print(f"  -> {long_csv_path}")
    print(f"  -> {aggr_csv_path}")

    total_traces = len(traces)
    per_judge: dict[str, dict] = {}
    for run_id, v in results_by_trace.items():
        for jr in v["judge_results"]:
            jid = jr["judge_id"]
            j_res = jr["result"]
            entry = per_judge.setdefault(jid, {
                "parse_failures": 0,
                "latency_sum_ms": 0,
                "prompt_tokens": 0,
                "completion_tokens": 0,
                "scores": [],
            })
            entry["latency_sum_ms"] += j_res.get("latency_ms", 0)
            entry["prompt_tokens"] += j_res.get("prompt_tokens", 0) or 0
            entry["completion_tokens"] += j_res.get("completion_tokens", 0) or 0
            if not j_res.get("success"):
                entry["parse_failures"] += 1
            elif j_res.get("score") is not None:
                entry["scores"].append(j_res["score"])

    # ── 6. JSON summary ───────────────────────────────────────────────────────
    if not args.skip_summary:
        summary_path = out_dir / "judge_benchmark_summary.json"

        per_judge_summary = {}
        for jid, e in per_judge.items():
            scores = e["scores"]
            per_judge_summary[jid] = {
                "model_description": judge_metadata.get(jid, {}).get("description", jid),
                "model_name": judge_metadata.get(jid, {}).get("name", jid),
                "model_params_b": judge_metadata.get(jid, {}).get("params_b"),
                "size_group": (
                    "small" if (judge_metadata.get(jid, {}).get("params_b") or 0) <= 4.0
                    else "large" if (judge_metadata.get(jid, {}).get("params_b") or 0) >= 7.0
                    else "medium_or_unclassified"
                ),
                "quant": judge_metadata.get(jid, {}).get("quant"),
                "estimated_memory_gb": judge_metadata.get(jid, {}).get("vram_gb"),
                "traces_scored": total_traces,
                "parse_failure_rate": round(e["parse_failures"] / total_traces, 4) if total_traces else 0,
                "mean_latency_ms": round(e["latency_sum_ms"] / total_traces, 1) if total_traces else 0,
                "model_load_ms": model_load_times_ms.get(jid),
                "total_prompt_tokens": e["prompt_tokens"],
                "total_completion_tokens": e["completion_tokens"],
                "n_valid_scores": len(scores),
                "mean_score": round(statistics.mean(scores), 4) if scores else None,
                "median_score": statistics.median(scores) if scores else None,
                "metric": JUDGE_METRIC,
            }

        summary = {
            "judge_schema_version": JUDGE_SCHEMA_VERSION,
            "metric": JUDGE_METRIC,
            "timestamp": datetime.utcnow().isoformat(),
            "scoring_concurrency": scoring_concurrency,
            "gpu_layers": n_gpu_layers,
            "hardware": hardware,
            "model_selection": {
                "source": "manual_override" if requested else "hardware_estimator",
                "context_length": args.context_length,
                "requested_quant": args.quant,
                "requested_judge_count": target_judge_count,
                "requested_small_judges": args.small_judges if not requested else None,
                "requested_large_judges": args.large_judges if not requested else None,
                "actual_small_judges": actual_small if not requested else None,
                "actual_large_judges": actual_large if not requested else None,
                "models_used": [
                    {
                        "judge_id": model["judge_id"],
                        "model_id": model["model_id"],
                        "name": model["name"],
                        "family": model.get("family"),
                        "params_b": model.get("params_b"),
                        "size_group": (
                            "small" if (model.get("params_b") or 0) <= 4.0
                            else "large" if (model.get("params_b") or 0) >= 7.0
                            else "medium_or_unclassified"
                        ),
                        "quant": model.get("quant"),
                        "estimated_memory_gb": model.get("vram_gb"),
                        "context_length": model.get("context_length", args.context_length),
                        "repo": model.get("repo"),
                    }
                    for model in loaded_judge_specs
                ],
            },
            "judges_used": judge_ids,
            "available_traces": len(all_traces),
            "total_traces": total_traces,
            "total_judge_evaluations": total_traces * len(judge_ids),
            "trace_sampling": {
                "strategy": "balanced_candidate_model_by_source_group" if args.sample_per_model_source else "all_successful_traces",
                "sample_per_model_source": args.sample_per_model_source,
                "seed": args.sample_seed,
                "available_traces": len(all_traces),
                "sampled_traces": total_traces,
                "strata_count": len(strata_counts),
                "strata": strata_counts,
            },
            "judge_panel_status": "complete" if judge_panel_complete else "partial",
            "experiment_dir": str(experiment_dir) if experiment_dir else None,
            "traces_path": str(traces_path),
            "per_judge": per_judge_summary,
            "per_judge_summary": per_judge_summary,
            "model_load_ms": model_load_times_ms,
        }

        with open(summary_path, "w", encoding="utf-8") as f:
            json.dump(summary, f, indent=2)
        print(f"  -> {summary_path}")

    if experiment_dir:
        manifest_path = experiment_dir / "run_manifest.json"
        if manifest_path.exists():
            try:
                manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
                manifest.setdefault("stage_status", {})["judging"] = (
                    "complete" if judge_panel_complete else "partial"
                )
                manifest.setdefault("paths", {})["judge_output"] = str(out_dir)
                manifest["judges_used"] = judge_ids
                manifest["judge_sampling"] = summary.get("trace_sampling", {}) if not args.skip_summary else {
                    "strategy": "balanced_candidate_model_by_source_group" if args.sample_per_model_source else "all_successful_traces",
                    "sample_per_model_source": args.sample_per_model_source,
                    "seed": args.sample_seed,
                    "available_traces": len(all_traces),
                    "sampled_traces": total_traces,
                    "strata_count": len(strata_counts),
                    "strata": strata_counts,
                }
                manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
            except (OSError, json.JSONDecodeError) as exc:
                logger.warning(f"Could not update experiment manifest: {exc}")

    # ── 7. Console summary ────────────────────────────────────────────────────
    print("\n" + "=" * 70)
    print("=== BENCHMARK COMPLETE ===")
    print("=" * 70)
    for jid in judge_ids:
        data = per_judge.get(jid, {})
        scores = data.get("scores", [])
        fails = data.get("parse_failures", 0)
        fail_pct = round(fails / total_traces * 100, 1) if total_traces else 0.0
        mean_s = round(statistics.mean(scores), 2) if scores else "n/a"
        print(
            f"  {jid:<20}  valid={len(scores)}/{total_traces}  "
            f"fail_rate={fail_pct}%  mean_score={mean_s}"
        )
    print("=" * 70 + "\n")


